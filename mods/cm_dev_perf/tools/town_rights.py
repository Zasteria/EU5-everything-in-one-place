#!/usr/bin/env python3
"""The town-rights mirror CM dev ships, rebuilt from the game's files.

CM dev's `cm_auto_town_rights_allow_triggers.txt` and
`cm_auto_town_rights_potential_triggers.txt` were generated by the author's own
script against 1.3 and say «Regenerate after a game update». That script is not
ours, so this rebuilds both in the same shape from `reference/game/`, base game
and every DLC folder: 1.4 added rights CM dev never saw, 1.4.5's Across the
Pillars adds more, and 1.4 dropped `imperial_breadbasket_rights`.

    python3 mods/cm_dev_perf/tools/town_rights.py     what moved against the mod

`port_from_cm_dev.py` writes the two files with `allow_text()` and
`potential_text()`, before its own edits on them run.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "tools"))

import refs  # noqa: E402

# The basic gate, checked at the call site via modifier:can_grant_town_rights.
BASE_ADVANCE = "city_building_advance"


@dataclass
class Right:
    name: str
    specialization: bool = False
    potential: str | None = None
    allow: str | None = None
    advances: list[str] = field(default_factory=list)


def _sources(sub: str) -> list[Path]:
    """Base game first, then each DLC: the order the engine reads them in."""
    files = sorted((refs.GAME_COMMON / sub).glob("*.txt"))
    for dlc in sorted((refs.GAME / "dlc").glob("*")):
        files += sorted((dlc / "in_game/common" / sub).glob("*.txt"))
    return files


def _strip_comments(text: str) -> str:
    return re.sub(r"#[^\n]*", "", text)


def _blocks(text: str):
    """(name, body) for each top-level `name = { ... }`, body without the outer braces."""
    i = 0
    for m in re.finditer(r"(?m)^([A-Za-z0-9_]+)\s*=\s*\{", text):
        if m.start() < i:
            continue
        depth, j = 1, m.end()
        while depth and j < len(text):
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        yield m.group(1), text[m.end():j - 1]
        i = j


def _child(body: str, key: str) -> str | None:
    """The body of the first direct child block `key = { ... }`."""
    depth = 0
    for m in re.finditer(r"\{|\}|\b" + key + r"\s*=\s*\{", body):
        tok = m.group(0)
        if tok == "{":
            depth += 1
        elif tok == "}":
            depth -= 1
        elif depth == 0:
            d, j = 1, m.end()
            while d:
                d += {"{": 1, "}": -1}.get(body[j], 0)
                j += 1
            return body[m.end():j - 1]
        else:
            depth += 1
    return None


def _reindent(body: str, tabs: int) -> str:
    """The block's lines at `tabs` deep, their own nesting kept."""
    lines = [l.rstrip() for l in body.strip("\n").splitlines() if l.strip()]
    if not lines:
        return ""
    cut = min(len(l) - len(l.lstrip("\t")) for l in lines)
    return "".join("\t" * tabs + l[cut:] + "\n" for l in lines)


def rights() -> list[Right]:
    found: dict[str, Right] = {}
    for path in _sources("town_rights"):
        text = _strip_comments(path.read_text(encoding="utf-8-sig"))
        for name, body in _blocks(text):
            found[name] = Right(
                name,
                specialization=bool(re.search(r"(?m)^\s*is_specialization\s*=\s*yes", body)),
                potential=_child(body, "potential"),
                allow=_child(body, "allow"),
            )
    for path in _sources("advances"):
        text = _strip_comments(path.read_text(encoding="utf-8-sig"))
        for advance, body in _blocks(text):
            for r in re.findall(r"unlock_town_rights\s*=\s*([A-Za-z0-9_]+)", body):
                if r in found and advance != BASE_ADVANCE and advance not in found[r].advances:
                    found[r].advances.append(advance)
    return list(found.values())


def _chain(entries: list[tuple[str, str]], tail: str) -> str:
    out = ""
    for n, (name, body) in enumerate(entries):
        out += ("\ttrigger_if = {\n" if n == 0 else "\ttrigger_else_if = {\n")
        out += f"\t\tlimit = {{ scope:cm_town_right = town_rights_type:{name} }}\n"
        out += body + "\t}\n"
    return out + tail


_ELSE = "\ttrigger_else = {\n\t\talways = yes\n\t}\n"

ALLOW_HEAD = """﻿# Generated by mods/cm_dev_perf/tools/town_rights.py from the game's files, in the
# shape of CM dev's own generator - do not edit by hand. Regenerate after a game update.
#
# Country trigger. Mirrors each vanilla town_rights_type `allow` block so auto-grant
# only grants a right on a location the engine would allow it on.
# Expects scope:cm_town_right (the right) and scope:target (the candidate location).
# Rights with no `allow` restriction fall through to the trailing trigger_else.
"""

SPEC_HEAD = """
# The same mirror over the royal specialization rights alone, the set the Auto-Grant
# Urban Rights draw picks from. Most of them carry no `allow` block, so answering
# through the chain above means walking every branch of it to reach the trigger_else.
# Expects scope:cm_town_right (the right) and scope:target (the candidate location).
"""

POTENTIAL_HEAD = """﻿# Generated by mods/cm_dev_perf/tools/town_rights.py from the game's files, in the
# shape of CM dev's own generator - do not edit by hand. Regenerate after a game update.
#
# Country trigger. Returns yes when the country currently meets the per-right
# prerequisites for the town right in scope:cm_town_right: the unlocking advance
# if any, plus the right's `potential` block if any.
# The basic city_building_advance gate is checked separately at the call site
# via modifier:can_grant_town_rights = yes.
# Rights with neither an advance nor a `potential` fall through to the trailing
# trigger_else.
"""


def allow_text(all_rights: list[Right] | None = None) -> str:
    all_rights = all_rights or rights()
    with_allow = [r for r in all_rights if r.allow and r.allow.strip()]
    general = _chain([(r.name, _reindent(r.allow, 2)) for r in with_allow], _ELSE)
    royal = [r for r in with_allow if r.specialization and r.name.startswith("royal_")]
    spec = _chain([(r.name, _reindent(r.allow, 2)) for r in royal], _ELSE)
    return (ALLOW_HEAD + "cm_can_grant_specific_town_right_at_location = {\n" + general + "}\n"
            + SPEC_HEAD + "cm_can_grant_specialization_right_at_location = {\n" + spec + "}\n")


def potential_text(all_rights: list[Right] | None = None) -> str:
    entries = []
    for r in all_rights or rights():
        body = "".join(f"\t\thas_advance = {a}\n" for a in r.advances)
        if r.potential and r.potential.strip():
            body += _reindent(r.potential, 2)
        if body:
            entries.append((r.name, body))
    return POTENTIAL_HEAD + "cm_auto_town_rights_potential_passes = {\n" + _chain(entries, _ELSE) + "}\n"


def _names(text: str) -> list[str]:
    return re.findall(r"limit = \{ scope:cm_town_right = town_rights_type:([a-z_0-9]+)", text)


def main() -> int:
    mod = refs.REPO / "mods/cm_dev_perf/in_game/common/scripted_triggers"
    all_rights = rights()
    print(f"{len(all_rights)} rights in the game, "
          f"{sum(r.specialization for r in all_rights)} of them specializations")
    for fname, new in (("cm_auto_town_rights_allow_triggers.txt", allow_text(all_rights)),
                       ("cm_auto_town_rights_potential_triggers.txt", potential_text(all_rights))):
        old = (mod / fname).read_text(encoding="utf-8-sig")
        o, n = _names(old), _names(new)
        print(f"{fname}: mod {len(o)} branches, game {len(n)}")
        print("   only in the mod:", sorted(set(o) - set(n)))
        print("   only in the game:", sorted(set(n) - set(o)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
