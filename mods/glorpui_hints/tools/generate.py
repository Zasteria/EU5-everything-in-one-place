def other_lines(findings: list[dict]) -> list[dict]:
    """Every push outside privileges, reforms and policies that the mod lists."""
    caches = {source: svx_gates.scan_objects(str(GAME), rel) for source, rel in SOURCE_DIRS.items()}
    status_owners = svx_gates.status_owners(str(GAME))
    auto_gates = auto_modifier_gates()
    known = core.steps(GAME)
    scaled = set(svx_languages.SCALED_KEYS) | set(svx_languages.NEW_SCALED_KEYS)
    conditional = set(svx_languages.CONDITIONAL_KEYS) | set(svx_languages.NEW_CONDITIONAL_KEYS)

    lines = []
    for row in findings:
        source, obj, axis = row["source_type"], row["object"], row["axis"]
        value = core.amount(row["raw_value"], known)
        if value is None or value <= 0 or source in CORE_SOURCES:
            continue
        base = {"direction": axis, "object": obj, "value": value, "up_to": False,
                "source_type": source, "soon": None}
        if source == "estates":
            # `high_power`: in force only above the power threshold, and scaled
            # past it, so the number is a ceiling (his note, 2026-09-28).
            base.update(kind="estate_power", up_to=True,
                        now=["country_has_estate = estate_type:%s" % obj])
        elif source in svx_languages.CATALOG_REGISTRIES:
            gate = svx_gates.gate_for(source, obj, caches.get(source, {}),
                                      {"status_owners": status_owners,
                                       "block": row["path"][1] if len(row["path"]) > 1 else ""})
            now, reach = list(gate["now"]), list(gate["reach"])
            if source in EXCLUSIVE_SOURCES:
                peers = sorted({other["object"] for other in findings
                                if other["source_type"] == source and other["axis"] == axis
                                and other["object"] != obj
                                and (core.amount(other["raw_value"], known) or 0) >= value})
                now += ["NOT = { has_employment_system = employment_system:%s }" % p
                        for p in peers + [obj]]
            base.update(kind="catalog", now=now, up_to=source in MAINTAINED_SOURCES)
            if source == "advances" and obj in ADVANCES.age:
                base["why"] = {"age": ADVANCES.age[obj]}
            # «Not yet» needs a real reach to be about: without one, failing
            # «now» means displaced or done, not pending.
            if reach and reach != now:
                base["soon"] = reach + ["NOT = { AND = { %s } }" % " ".join(now)]
        elif obj in scaled or obj in conditional:
            base.update(kind="scaled" if obj in scaled else "conditional",
                        up_to=obj in scaled,
                        now=[auto_gates[obj]] if obj in auto_gates else [])
        elif obj.endswith(CABINET_SUFFIX):
            base.update(kind="cabinet", now=[])
        else:
            continue
        lines.append(base)
    return lines


def collect() -> dict[str, list[dict]]:
    """direction -> its lines, takeable kinds first, each kind strongest first."""
    lines = core.collect(GAME) + other_lines(scan_sources.scan(str(GAME)))
    order = {"privilege": 0, "reform": 1, "policy": 2, "io_policy": 3, "estate_power": 4,
             "catalog": 5, "scaled": 6, "conditional": 7, "cabinet": 8}
    out: dict[str, list[dict]] = collections.defaultdict(list)
    seen = set()
    for line in sorted(lines, key=lambda l: (order[l["kind"]], -l["value"], l["object"])):
        identity = (line["direction"], line["kind"], line.get("source_type"), line["object"])
        if identity in seen:
            continue
        seen.add(identity)
        code = LINE_CODE[line["kind"]]
        line["name"] = "svx_%s_%s_%s" % (line["direction"], code, line["object"])
        out[line["direction"]].append(line)
    return out


def line_text(line: dict, lang: str, glorp: dict[str, dict[str, str]]) -> str:
    phrases = svx_languages.PHRASES[lang]
    value = (phrases["up_to"] if line["up_to"] else "") + number(line["value"])
    kind = line["kind"]
    if kind in ("privilege", "reform", "policy"):
        return glorp[lang][kind].replace("{key}", line["object"]).replace("{value}", value)
    if kind == "io_policy":
        label = phrases["io_policy"].format(ref="[ShowPolicyName('%s')]" % line["object"])
        return "@hint! %s: #color_green %s#!\\n" % (label, value)
    if kind == "estate_power":
        # «Власть священников выше порога: до +0.33» — the game's own name for
        # the estate's power, through a data function, inside words of our own.
        label = phrases["estate_power"].format(
            ref="[ShowModifierTypeName('global_%s_power')]" % line["object"])
        return "@hint! %s: #color_green %s#!\\n" % (label, value)
    if kind == "catalog":
        source = line["source_type"]
        reference = "#TOOLTIP:%s,%s #L $%s$#!#!" % (
            svx_languages.CATALOG_REGISTRIES[source], line["object"], line["object"])
        concept = svx_languages.CATALOG_CONCEPTS.get(source)
        if concept is None:
            label = "%s %s" % (phrases["build_in_capital"], reference)
        else:
            label = phrases["catalog"].format(concept=concept, ref=reference)
        return "@hint! %s: #color_green %s#!\\n" % (label, value)
    if kind == "scaled":
        return "@hint! %s #help (%s)#!: #color_green %s#!\\n" % (
            phrases["scaled"][line["object"]], phrases["scales"], value)
    if kind == "conditional":
        return "@hint! %s: #color_green %s#!\\n" % (phrases["conditional"][line["object"]], value)
    if kind == "cabinet":
        return "@hint! %s #help (%s)#!\\n" % (phrases["cabinet"], phrases["cabinet_scales"])
    raise AssertionError(kind)


