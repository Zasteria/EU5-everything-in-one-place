def fail(message: str) -> None:
    raise SystemExit("generate.py: " + message)


def number(value: float) -> str:
    text = ("%.3f" % value).rstrip("0")
    if len(text.split(".")[1]) < 2:
        text = "%.2f" % value
    return "+" + text


def glorp_lines(glorp: Path) -> dict[str, dict[str, str]]:
    """language -> kind -> Glorp UI's line, with `{key}` and `{value}` holes.

    Every line of one kind in one language must reduce to the same shape;
    anything else means Glorp UI changed how it writes them, and the build stops
    rather than wording a line some other way.
    """
    out: dict[str, dict[str, str]] = {}
    line = re.compile(r'^ GLORP_UI_SVH_[A-Z_]+?_(PV|R|P)_[A-Z0-9_]+: *"(.*)"\s*$', re.M)
    for lang in svx_languages.LANGUAGES:
        path = glorp / GLORP_HINTS.format(lang=lang)
        if not path.is_file():
            fail("%s missing — is Glorp UI in reference/mods?" % path)
        shapes: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
        for match in line.finditer(path.read_text(encoding="utf-8-sig")):
            text = re.sub(r"(\[Show\w+Name)\('\w+'\)", r"\1('{key}')", match.group(2))
            text = re.sub(r"[+]\d+\.\d+", "{value}", text, count=1)
            shapes[GLORP_CODES[match.group(1)]][text] += 1
        out[lang] = {}
        for kind in GLORP_CODES.values():
            found = shapes.get(kind)
            if not found or len(found) != 1:
                fail("%s: %s lines come in %d shapes, expected one: %s"
                     % (path.name, kind, len(found or {}), list(found or {})[:3]))
            out[lang][kind] = next(iter(found))
    return out


