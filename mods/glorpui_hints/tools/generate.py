#!/usr/bin/env python3
"""Build `glorpui_hints` from the game's own files, worded as Glorp UI words it.

    python3 mods/glorpui_hints/tools/generate.py           write the mod
    python3 mods/glorpui_hints/tools/generate.py --check   write nothing, say what would change

What the societal value tooltip lists, per direction:

* **Off** (the usual): under the game's own «To further push» title, what the
  country can take or already has working for it today; under the game's own
  «Not yet available» title, what it could get later. Both lists come from the
  game's `common/`: privileges, reforms and policies (`core.py`), and every other
  source that pushes a value (`gates.py`, `languages.py`).
  Each «not yet» row opens with its age, «(IV)», a link to what it takes.
* **On** — Glorp UI's «show unavailable suggestions» switch, or this mod's own in
  the CMF menu, either one: the same two lists, then what this country can never
  take (linked the same way: whose it is shows in its conditions), then every
  other source unfiltered.

**With Glorp UI and without it.** Every name the mod defines is its own
(`svx_*`), so nothing collides with Glorp UI's and nothing needs it at runtime.
Glorp UI's part is the wording: the privilege, reform and policy lines are built
from Glorp UI's own hint files in all eleven languages, read here at build time,
and its switch is honoured. The template this mod overrides is the one Glorp UI
overrides too, so with both installed this mod has to load after Glorp UI.
"""

