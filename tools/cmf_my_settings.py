#!/usr/bin/env python3
"""The «my settings» mod, built from a saved CMF settings block.

`mods/cmf_saved_settings` prints every CMF setting into `debug.log` as a block of
`CMFSAVE` lines; `mods.bat` → 5 lifts it into a file and calls this to turn it
into a local mod, `cmf_my_settings`, in the game's mod folder. **The game can
read nothing else**: a mod cannot write a file or read another save
(docs/research/engine_reach.md), so the way back in is script in a mod folder.

What the mod does, once per new game:

- **Only in a game started with it on.** `on_game_started_after_lobby` raises
  `bag_cmfm_new_game`; a loaded old save never has it, so his settings there
  are never touched.
- **Each key once.** A value is written only when CMF has registered the key
  (it is in the `cmm` map) and only the first time; the mark lives in the save,
  so what he changes later in the game stays. A key that a mod registers later
  — a newer mod version — is caught on the next registration pass.
- **Then the mod is told.** One `cmf_on_callback` per setting that changed, as
  CMF's own «Сбросить» does, so aliases and the mods' own reactions follow.
- **Ordered lists are put back in the saved order**, items the save does not
  know (a mod update) after them; `cmf_dev_beta`'s place numbers are dropped so
  it falls back to the row index.

    python3 tools/cmf_my_settings.py <last.txt> <mod folder>   build by hand
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from collections import OrderedDict
from pathlib import Path

FOLDER = "cmf_my_settings"
BOM = "﻿"

# A plain setting is `<mod>__<setting>`; a list field `<mod>__<setting>_i<N>_f<slot>`.
KEY = re.compile(r"^\w+__\w+$")
FIELD = re.compile(r"^(\w+__\w+?)_i\d+_f\d+$")
ROW = re.compile(r"^CMFSAVE ([cg]) (-?[\d.]+) (\w+)$")
ORDER = re.compile(r"^CMFSAVE order ((\w+__\w+?)_i\d+)$")


def parse(lines: list[str]) -> tuple[dict, dict, list[str]]:
    """values[(kind, key)] = number, order[setting] = [item flags], skipped keys."""
    values: dict[tuple[str, str], str] = OrderedDict()
    order: dict[str, list[str]] = OrderedDict()
    skipped: list[str] = []
    for raw in lines:
        line = raw.strip()
        row = ROW.match(line)
        if row:
            kind, number, key = row.groups()
            # `cmm_init` is CMF's own bookkeeping, and the saver's button is not
            # a setting anybody wants carried over.
            if not KEY.match(key) or key.startswith("bag_cmfs__"):
                skipped.append(key)
                continue
            values[(kind, key)] = number
            continue
        item = ORDER.match(line)
        if item:
            order.setdefault(item.group(2), []).append(item.group(1))
    return values, order, skipped


def number(text: str) -> str:
    value = float(text)
    return str(int(value)) if value == int(value) else ("%.3f" % value).rstrip("0")


def owner(key: str) -> str:
    field = FIELD.match(key)
    return field.group(1) if field else key


def apply_effect(values: dict, order: dict) -> str:
    out = ["# Scope: country (a human). Generated by tools/cmf_my_settings.py — do not edit.",
           "bag_cmfm_apply = {",
           "\tsave_scope_as = bag_cmfm_owner"]
    by_setting: dict[tuple[str, str], list[tuple[str, str]]] = OrderedDict()
    for (kind, key), value in values.items():
        by_setting.setdefault((kind, owner(key)), []).append((key, value))

    for (kind, setting), keys in by_setting.items():
        g = "global_" if kind == "g" else ""
        out.append("\t# %s" % setting)
        out.append("\tset_local_variable = { name = bag_cmfm_touched value = 0 }")
        for key, value in keys:
            out += [
                "\tif = {",
                "\t\tlimit = {",
                "\t\t\tis_key_in_%svariable_map = { name = cmm target = flag:%s }" % (g, key),
                "\t\t\tNOT = { is_key_in_%svariable_map = { name = bag_cmfm_done target = flag:%s } }" % (g, key),
                "\t\t}",
                # CMF itself removes before it adds (cmm_core_auto_apply_scripted_gui).
                "\t\tremove_from_%svariable_map = { name = cmm key = flag:%s }" % (g, key),
                "\t\tadd_to_%svariable_map = { name = cmm key = flag:%s value = %s }" % (g, key, number(value)),
                "\t\tadd_to_%svariable_map = { name = bag_cmfm_done key = flag:%s value = 1 }" % (g, key),
                "\t\tset_local_variable = { name = bag_cmfm_touched value = 1 }",
                "\t\tchange_global_variable = { name = bag_cmfm_applied add = 1 }",
                "\t}",
            ]
        out += [
            "\tif = {",
            "\t\tlimit = { local_var:bag_cmfm_touched = 1 }",
            "\t\tbag_cmfm_callback = { setting = %s }" % setting,
            "\t}",
        ]

    for setting, items in order.items():
        out += [
            "\t# order of %s" % setting,
            "\tif = {",
            "\t\tlimit = {",
            "\t\t\thas_variable_list = cmm_list_items_%s" % setting,
            "\t\t\tNOT = { is_key_in_variable_map = { name = bag_cmfm_done target = flag:%s } }" % setting,
            "\t\t}",
            "\t\tclear_variable_list = bag_cmfm_tmp",
            "\t\tevery_in_list = {",
            "\t\t\tvariable = cmm_list_items_%s" % setting,
            "\t\t\tsave_scope_as = bag_cmfm_item",
            "\t\t\tscope:bag_cmfm_owner = { add_to_variable_list = { name = bag_cmfm_tmp target = scope:bag_cmfm_item } }",
            "\t\t}",
            "\t\tclear_variable_list = cmm_list_items_%s" % setting,
        ]
        for item in items:
            out += [
                "\t\tif = {",
                "\t\t\tlimit = { is_target_in_variable_list = { name = bag_cmfm_tmp target = flag:%s } }" % item,
                "\t\t\tadd_to_variable_list = { name = cmm_list_items_%s target = flag:%s }" % (setting, item),
                "\t\t}",
            ]
        out += [
            "\t\tevery_in_list = {",
            "\t\t\tvariable = bag_cmfm_tmp",
            "\t\t\tsave_scope_as = bag_cmfm_item",
            "\t\t\tscope:bag_cmfm_owner = {",
            "\t\t\t\tif = {",
            "\t\t\t\t\tlimit = { NOT = { is_target_in_variable_list = { name = cmm_list_items_%s target = scope:bag_cmfm_item } } }" % setting,
            "\t\t\t\t\tadd_to_variable_list = { name = cmm_list_items_%s target = scope:bag_cmfm_item }" % setting,
            "\t\t\t\t}",
            "\t\t\t}",
            "\t\t}",
            "\t\tclear_variable_list = bag_cmfm_tmp",
            "\t\t# cmf_dev_beta numbers the rows in cmf_beta_list_place; without an",
            "\t\t# entry it shows the row index, which is right after a rebuild.",
            "\t\tif = {",
            "\t\t\tlimit = { has_variable_map = cmf_beta_list_place }",
        ]
        for item in items:
            out += [
                "\t\t\tif = {",
                "\t\t\t\tlimit = { is_key_in_variable_map = { name = cmf_beta_list_place target = flag:%s } }" % item,
                "\t\t\t\tremove_from_variable_map = { name = cmf_beta_list_place key = flag:%s }" % item,
                "\t\t\t}",
            ]
        out += [
            "\t\t}",
            "\t\tadd_to_variable_map = { name = bag_cmfm_done key = flag:%s value = 1 }" % setting,
            "\t\tchange_global_variable = { name = bag_cmfm_applied add = 1 }",
            "\t\tbag_cmfm_callback = { setting = %s }" % setting,
            "\t}",
        ]
    out.append("}")
    return "\n".join(out) + "\n"


STATIC_EFFECTS = """# Scope: country. Tell the mods a setting changed, the way CMF's own reset does
# (`_cmm_fire_reset_callback`): cmf_callback holds the setting's flag.
bag_cmfm_callback = {
\tset_variable = { name = cmf_callback value = flag:$setting$ }
\ttrigger_event_silently = { on_action = cmf_on_callback }
\tremove_variable = cmf_callback
}

# Scope: country. One pass, and one line in debug.log saying what it did.
bag_cmfm_pass = {
\tset_global_variable = { name = bag_cmfm_applied value = 0 }
\tbag_cmfm_apply = yes
\tdebug_log = "CMFMY pass applied=[GuiScope.SetRoot(GetPlayer.MakeScope).ScriptValue('bag_cmfm_applied_sv')|0] of %(total)d"
}
"""

ON_ACTIONS = """# Generated by tools/cmf_my_settings.py from his saved settings — do not edit.
#
# A new game raises bag_cmfm_new_game; only then do the passes write anything,
# so a loaded old save is never touched. Three passes, because which of them
# comes after every mod's registration is not measured: the new game itself,
# CMF's after-lobby hook, and every registration pass (each key is written
# once, so the later passes only catch keys that were not registered yet).

on_game_started_after_lobby = {
\ton_actions = {
\t\tbag_cmfm_on_new_game
\t}
}

# Scope: none
bag_cmfm_on_new_game = {
\teffect = {
\t\tset_global_variable = { name = bag_cmfm_new_game value = yes }
\t\tevery_country = {
\t\t\tlimit = { is_ai = no }
\t\t\tbag_cmfm_pass = yes
\t\t}
\t}
}

on_game_start_after_lobby = {
\ton_actions = {
\t\tbag_cmfm_on_after_lobby
\t}
}

# Scope: none
bag_cmfm_on_after_lobby = {
\teffect = {
\t\tif = {
\t\t\tlimit = { has_global_variable = bag_cmfm_new_game }
\t\t\tevery_country = {
\t\t\t\tlimit = { is_ai = no }
\t\t\t\tbag_cmfm_pass = yes
\t\t\t}
\t\t}
\t}
}

cmf_on_mod_registration = {
\ton_actions = {
\t\tbag_cmfm_on_register
\t}
}

# Scope: country
bag_cmfm_on_register = {
\teffect = {
\t\tif = {
\t\t\tlimit = { has_global_variable = bag_cmfm_new_game }
\t\t\tbag_cmfm_pass = yes
\t\t}
\t}
}
"""

VALUES = """bag_cmfm_applied_sv = {
\tvalue = global_var:bag_cmfm_applied
}
"""


def write_mod(lines: list[str], target: Path, source: str) -> dict:
    """Build the mod into `target` (replaced whole). Returns what went in."""
    values, order, skipped = parse(lines)
    if target.exists():
        shutil.rmtree(target)
    common = target / "in_game/common"
    for sub in ("on_action", "scripted_effects", "script_values"):
        (common / sub).mkdir(parents=True, exist_ok=True)
    (target / ".metadata").mkdir(parents=True, exist_ok=True)
    meta = {
        "name": "CMF: мои настройки",
        "id": "bag.cmf_my_settings",
        "version": "1.0.0",
        "game_id": "eu5",
        "supported_game_version": "1.4.*",
        "short_description": "Generated by mods.bat from %s: puts these CMF settings into every new game." % source,
        "tags": ["Utilities"],
        "relationships": [{"rel_type": "dependency", "id": "community_mod_framework",
                           "display_name": "Community Mod Framework",
                           "resource_type": "mod", "version": "2.*"}],
        "game_custom_data": {},
    }
    (target / ".metadata/metadata.json").write_text(
        BOM + json.dumps(meta, indent=4, ensure_ascii=False) + "\n", encoding="utf-8")
    total = len(values) + len(order)
    (common / "on_action/bag_cmfm_on_actions.txt").write_text(BOM + ON_ACTIONS, encoding="utf-8")
    (common / "scripted_effects/bag_cmfm_effects.txt").write_text(
        BOM + STATIC_EFFECTS % {"total": total} + "\n" + apply_effect(values, order), encoding="utf-8")
    (common / "script_values/bag_cmfm_values.txt").write_text(BOM + VALUES, encoding="utf-8")
    return {"values": len(values), "lists": len(order), "skipped": skipped,
            "mods": sorted({key.split("__")[0] for _, key in values})}


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    source = Path(argv[1])
    report = write_mod(source.read_text(encoding="utf-8").splitlines(), Path(argv[2]), source.name)
    print(report)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
